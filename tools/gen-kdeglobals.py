#!/usr/bin/env python3
"""Merge the VeyraOS Light colour scheme into /etc/xdg/kdeglobals.

Plasma reads the actual colours from the [Colors:*] groups of kdeglobals;
naming a scheme in [General] ColorScheme= is not enough for new users until
the scheme is applied once. Shipping the full groups in the system-wide
kdeglobals makes every new account start in VeyraOS colours.

    tools/gen-kdeglobals.py      (rewrites src/desktop/etc/xdg/kdeglobals)
"""
import os
import re

TOP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(TOP, "src/desktop/etc/xdg/kdeglobals.base")
SCHEME = os.path.join(TOP, "src/desktop/usr/share/color-schemes/VeyraLight.colors")
OUT = os.path.join(TOP, "src/desktop/etc/xdg/kdeglobals")


def groups(text):
    out, cur = {}, None
    for line in text.splitlines():
        m = re.match(r"^(\[.*\])\s*$", line)
        if m:
            cur = m.group(1)
            out.setdefault(cur, [])
        elif cur and line.strip() and not line.startswith("#"):
            out[cur].append(line)
    return out


base = groups(open(BASE).read())
scheme = groups(open(SCHEME).read())
for g, lines in scheme.items():
    # base settings win; scheme fills in every key the base does not set
    keys = {l.split("=", 1)[0] for l in base.get(g, [])}
    base.setdefault(g, []).extend(l for l in lines
                                  if l.split("=", 1)[0] not in keys and not l.startswith("Name="))
with open(OUT, "w") as f:
    f.write("# Generated by tools/gen-kdeglobals.py from kdeglobals.base + VeyraLight.colors — edit those.\n")
    for g, lines in base.items():
        f.write(g + "\n" + "\n".join(lines) + "\n\n")
print("wrote", OUT)
