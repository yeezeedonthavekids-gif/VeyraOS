# shellcheck shell=bash
# ISO image assembly. Shared by build-iso.sh and tests/boot/run-boot-test.sh so
# the exact same GRUB menu and image layout are exercised by the boot test.
#
# ISO layout:
#   /boot/vmlinuz-<kernel>            kernel(s)
#   /boot/initramfs-<kernel>.img      live initramfs (contains the veyralive hook)
#   /boot/{amd,intel}-ucode.img       CPU microcode (optional)
#   /boot/grub/grub.cfg               menu (BIOS + UEFI)
#   /boot/grub/themes/veyra/          GRUB theme (optional)
#   /veyra/x86_64/rootfs.sfs          the root filesystem
#   /veyra/x86_64/rootfs.sha512       integrity checksum (veyra.verify=1)
#   /veyra/version                    release identification

# write_grub_cfg <isodir> <label> <cmdline> <kernel...>
write_grub_cfg() {
    local isodir=$1 label=$2 cmdline=$3; shift 3
    local -a kernels=("$@")
    local cfg=$isodir/boot/grub/grub.cfg
    local name=${VEYRA_NAME:-VeyraOS} version=${VEYRA_VERSION:-dev}
    local ucode='' u k
    for u in amd-ucode.img intel-ucode.img; do
        [[ -f $isodir/boot/$u ]] && ucode+=" /boot/$u"
    done
    mkdir -p "$(dirname "$cfg")"

    {
        cat <<EOF
# ${name} ${version} live medium — generated by build/lib/iso.sh
insmod part_gpt
insmod part_msdos
insmod iso9660
insmod all_video
insmod gfxterm
insmod png
insmod font

search --no-floppy --set=root --label ${label}

set default=0
set timeout=10
set timeout_style=menu

if loadfont /boot/grub/fonts/unicode.pf2 ; then
    set gfxmode=auto
    set gfxpayload=keep
    terminal_output gfxterm
fi
if [ -f /boot/grub/themes/veyra/theme.txt ] ; then
    set theme=/boot/grub/themes/veyra/theme.txt
else
    set menu_color_normal=light-gray/black
    set menu_color_highlight=white/blue
fi

EOF
        local first=1
        for k in "${kernels[@]}"; do
            [[ -f $isodir/boot/vmlinuz-$k ]] || continue
            local suffix=''
            ((first)) || suffix=" — ${k} kernel"
            cat <<EOF
menuentry "Start ${name} ${version}${suffix}" --class veyra --class gnu-linux --id veyra-${k} {
    linux /boot/vmlinuz-${k} veyra.label=${label} ${cmdline}
    initrd${ucode} /boot/initramfs-${k}.img
}
EOF
            if ((first)); then
                cat <<EOF
menuentry "Start ${name} — load into RAM (frees the USB drive)" --class veyra --id veyra-ram {
    linux /boot/vmlinuz-${k} veyra.label=${label} veyra.copytoram=1 ${cmdline}
    initrd${ucode} /boot/initramfs-${k}.img
}
submenu "Troubleshooting >" --class recovery {
    menuentry "Safe graphics (nomodeset, no GPU driver)" --class recovery {
        linux /boot/vmlinuz-${k} veyra.label=${label} nomodeset module_blacklist=nvidia,nvidia_drm,nvidia_modeset,nvidia_uvm quiet loglevel=3
        initrd${ucode} /boot/initramfs-${k}.img
    }
    menuentry "Text mode rescue console (no desktop)" --class recovery {
        linux /boot/vmlinuz-${k} veyra.label=${label} softlevel=text loglevel=4
        initrd${ucode} /boot/initramfs-${k}.img
    }
    menuentry "Verify medium integrity, then start" --class recovery {
        linux /boot/vmlinuz-${k} veyra.label=${label} veyra.verify=1 ${cmdline/quiet/}
        initrd${ucode} /boot/initramfs-${k}.img
    }
    menuentry "Verbose boot (show all messages)" --class recovery {
        linux /boot/vmlinuz-${k} veyra.label=${label} nvidia_drm.modeset=1 loglevel=7
        initrd${ucode} /boot/initramfs-${k}.img
    }
}
EOF
                first=0
            fi
        done
        cat <<'EOF'
if [ "$grub_platform" = "efi" ] ; then
    if [ -f /boot/memtest86+/memtest.efi ] ; then
        menuentry "Memory test (memtest86+)" --class memtest {
            chainloader /boot/memtest86+/memtest.efi
        }
    fi
    menuentry "UEFI firmware settings" --class settings {
        fwsetup
    }
fi
menuentry "Restart" --class restart {
    reboot
}
menuentry "Shut down" --class shutdown {
    halt
}
EOF
    } > "$cfg"
}

# make_iso <isodir> <out.iso> <label>
# Hybrid image bootable on BIOS and UEFI, from optical media or USB (dd).
make_iso() {
    local isodir=$1 out=$2 label=$3
    require_cmd grub-mkrescue xorriso mformat
    rm -f "$out"
    # SOURCE_DATE_EPOCH makes xorriso timestamps deterministic.
    local -a extra=()
    if [[ -n ${SOURCE_DATE_EPOCH:-} ]]; then
        local d; d=$(date -u -d "@$SOURCE_DATE_EPOCH" +%Y%m%d%H%M%S00)
        extra=(-volume_date uuid "$d" -volume_date all_file_dates "=$SOURCE_DATE_EPOCH")
    fi
    grub-mkrescue \
        --product-name="${VEYRA_NAME:-VeyraOS}" --product-version="${VEYRA_VERSION:-dev}" \
        --compress=xz \
        -o "$out" "$isodir" -- \
        -volid "$label" \
        -publisher "${ISO_PUBLISHER:-VeyraOS}" \
        -application_id "${ISO_APPLICATION:-VeyraOS}" \
        "${extra[@]}" \
        || die "grub-mkrescue failed"
    [[ -s $out ]] || die "ISO was not created"
}

# write_checksums <file>
write_checksums() {
    local f=$1
    ( cd "$(dirname "$f")" && sha256sum "$(basename "$f")" > "$(basename "$f").sha256" \
                           && sha512sum "$(basename "$f")" > "$(basename "$f").sha512" )
}
